    const FRANCE_GRID_CLIP_RINGS = [FRANCE_GRID_CLIP_MAINLAND_RING, FRANCE_GRID_CLIP_CORSICA_RING];

    function nearlySamePoint(a, b) {
      return Math.abs(Number(a?.[0]) - Number(b?.[0])) < 1e-10 && Math.abs(Number(a?.[1]) - Number(b?.[1])) < 1e-10;
    }

    function closePolygonRing(ring) {
      if (!Array.isArray(ring) || ring.length < 3) return [];
      const cleaned = [];
      for (const point of ring) {
        if (!cleaned.length || !nearlySamePoint(cleaned[cleaned.length - 1], point)) cleaned.push(point);
      }
      if (cleaned.length < 3) return [];
      if (!nearlySamePoint(cleaned[0], cleaned[cleaned.length - 1])) cleaned.push([...cleaned[0]]);
      return cleaned;
    }

    function polygonRingArea(ring) {
      const closed = closePolygonRing(ring);
      if (closed.length < 4) return 0;
      let area = 0;
      for (let i = 0; i < closed.length - 1; i += 1) {
        area += closed[i][0] * closed[i + 1][1] - closed[i + 1][0] * closed[i][1];
      }
      return Math.abs(area / 2);
    }

    function pointInRing(lon, lat, ring) {
      let inside = false;
      let j = ring.length - 1;
      for (let i = 0; i < ring.length; i += 1) {
        const [xi, yi] = ring[i];
        const [xj, yj] = ring[j];
        const intersects = ((yi > lat) !== (yj > lat))
          && (lon < ((xj - xi) * (lat - yi) / ((yj - yi) || 1e-12)) + xi);
        if (intersects) inside = !inside;
        j = i;
      }
      return inside;
    }

    function pointInFranceGridMask(lon, lat) {
      return FRANCE_GRID_CLIP_RINGS.some((ring) => pointInRing(lon, lat, ring));
    }

    function shouldUseFranceGridClip(cells = null) {
      const slot = typeof getCurrentSlot === 'function' ? getCurrentSlot() : null;
      if (slot?.country_mask === 'france' || slot?.grid_scope === 'france' || slot?.france_grid) return true;
      const slotCells = Array.isArray(cells) ? cells : (Array.isArray(slot?.cells) ? slot.cells : []);
      return slotCells.length > 500 && slotCells.some((cell) => cell?.source_provider === 'meteofrance_arome_grib');
    }

    function intersectSegmentAtLon(a, b, lon) {
      const t = (lon - a[0]) / ((b[0] - a[0]) || 1e-12);
      return [lon, a[1] + (b[1] - a[1]) * t];
    }

    function intersectSegmentAtLat(a, b, lat) {
      const t = (lat - a[1]) / ((b[1] - a[1]) || 1e-12);
      return [a[0] + (b[0] - a[0]) * t, lat];
    }

    function clipOpenPolygonByBoundary(points, inside, intersect) {
      if (!Array.isArray(points) || !points.length) return [];
      const output = [];
      let previous = points[points.length - 1];
      let previousInside = inside(previous);
      for (const current of points) {
        const currentInside = inside(current);
        if (currentInside) {
          if (!previousInside) output.push(intersect(previous, current));
          output.push(current);
        } else if (previousInside) {
          output.push(intersect(previous, current));
        }
        previous = current;
        previousInside = currentInside;
      }
      return output;
    }

    function clipRingToRect(ring, minLon, minLat, maxLon, maxLat) {
      let points = closePolygonRing(ring).slice(0, -1);
      points = clipOpenPolygonByBoundary(points, (p) => p[0] >= minLon, (a, b) => intersectSegmentAtLon(a, b, minLon));
      points = clipOpenPolygonByBoundary(points, (p) => p[0] <= maxLon, (a, b) => intersectSegmentAtLon(a, b, maxLon));
      points = clipOpenPolygonByBoundary(points, (p) => p[1] >= minLat, (a, b) => intersectSegmentAtLat(a, b, minLat));
      points = clipOpenPolygonByBoundary(points, (p) => p[1] <= maxLat, (a, b) => intersectSegmentAtLat(a, b, maxLat));
      const clipped = closePolygonRing(points);
      return polygonRingArea(clipped) > 1e-9 ? clipped : null;
    }

    function rectangleRing(minLon, minLat, maxLon, maxLat) {
      return [[minLon, minLat], [maxLon, minLat], [maxLon, maxLat], [minLon, maxLat], [minLon, minLat]];
    }

    function clippedFranceCellGeometry(minLon, minLat, maxLon, maxLat) {
      const corners = rectangleRing(minLon, minLat, maxLon, maxLat).slice(0, -1);
      if (corners.every(([lon, lat]) => pointInFranceGridMask(lon, lat))) {
        return { type: 'Polygon', coordinates: [rectangleRing(minLon, minLat, maxLon, maxLat)] };
      }
      const clipped = FRANCE_GRID_CLIP_RINGS
        .map((ring) => clipRingToRect(ring, minLon, minLat, maxLon, maxLat))
        .filter(Boolean);
      if (!clipped.length) return null;
      if (clipped.length === 1) return { type: 'Polygon', coordinates: [clipped[0]] };
      return { type: 'MultiPolygon', coordinates: clipped.map((ring) => [ring]) };
    }

